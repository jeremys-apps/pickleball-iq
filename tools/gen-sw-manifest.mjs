// Regenerates app/sw-manifest.js: the list of files the service worker caches
// and a content hash, so every deploy with changed files gets a fresh cache.
// Run after changing anything in app/: npm run sw
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const APP = fileURLToPath(new URL('../app/', import.meta.url));
const SKIP = new Set(['sw.js', 'sw-manifest.js']);
const walk = (dir) => readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : [join(dir, n)]));

const files = walk(APP)
  .map((p) => relative(APP, p).split(sep).join('/'))
  .filter((f) => !SKIP.has(f) && !/(^|\/)(LICENSE|[^/]+\.txt)$/.test(f) && f !== 'data/deck.json' && !f.startsWith('.'))
  .sort();

const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(APP, f)));
const version = hash.digest('hex').slice(0, 12);

writeFileSync(
  join(APP, 'sw-manifest.js'),
  `// Generated by tools/gen-sw-manifest.mjs. Do not edit by hand.\nself.PIQ_VERSION = '${version}';\nself.PIQ_SHELL = ${JSON.stringify(['./', ...files], null, 2)};\n`,
);
console.log(`sw-manifest.js: ${files.length} files, version ${version}`);
